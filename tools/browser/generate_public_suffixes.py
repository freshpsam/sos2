#!/usr/bin/env python3
"""Regenerate the compiled PSL from the vendored upstream list (requires idna)."""
import hashlib
import json
from pathlib import Path
import idna

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'third_party/publicsuffix'

def main():
    source=BASE/'public_suffix_list.dat'
    rules=[]
    for line in source.read_text().splitlines():
        rule=line.strip()
        if not rule or rule.startswith('//'):continue
        prefix='*.' if rule.startswith('*.') else '!' if rule.startswith('!') else ''
        domain=rule[len(prefix):]
        rules.append(prefix+idna.encode(domain,uts46=True,transitional=False,std3_rules=True).decode('ascii'))
    output=BASE/'rules.inc'
    output.write_text('// Generated by tools/browser/generate_public_suffixes.py. MPL-2.0; see UPSTREAM.md.\n'+
        ''.join(json.dumps(rule)+',\n' for rule in sorted(set(rules))))
    record={'source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
            'rules_sha256':hashlib.sha256(output.read_bytes()).hexdigest(),
            'idna_version':idna.__version__,'rules':len(set(rules))}
    (BASE/'manifest.json').write_text(json.dumps(record,indent=2)+'\n')
    print(json.dumps(record,indent=2))

if __name__=='__main__':main()
