#!/usr/bin/env python3
"""Generate closed, integer-only A3xx display/copy kernels (no user shaders).

Encoding reference: freedreno/freedreno includes/instr-a3xx.h, Rob Clark,
MIT. See boards/redmi2/adreno-notices.txt. No compiler runs on the phone.
The readable assembly and binary are generated together.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OP = {'add.u': 16, 'and.b': 28, 'or.b': 29, 'mul.u': 48, 'shl.b': 54, 'shr.b': 55}


def register(s):
    return int(s[1:-2]) * 4 + 'xyzw'.index(s[-1])


def source(s):
    if s.startswith('c'):
        return register(s) | 0x1000
    if s.startswith('r'):
        return register(s)
    n = int(s, 0)
    if not 0 <= n <= 1023:
        raise ValueError(f'immediate out of range: {s}')
    return n | 0x2000


def shader(fmt):
    words, assembly = [], []

    def emit(lo, hi, text):
        words.extend((lo, hi))
        assembly.append(text)

    def nop(repeat=2, sy=False):
        emit(0, repeat << 8 | int(sy) << 28, f"{'(sy)' if sy else ''}(rpt{repeat})nop")

    def alu(op, dst, a, b, sy=False, ss=False):
        emit(source(a) | source(b) << 16,
             register(dst) | int(ss) << 12 | 1 << 20 | OP[op] << 21 | int(sy) << 28 | 2 << 29,
             f"{'(sy)' if sy else ''}{'(ss)' if ss else ''}{op} {dst}, {a}, {b}")

    def store(kind, count=1, sy=False):
        # STG: destination is the address register, src1 the value register,
        # src2 an immediate scalar count. U8/U16 consume low bits of full GPRs.
        emit(register('r3.x') << 1 | 1 << 23 | count << 24,
             register('r2.z') | kind << 17 | 3 << 22 | int(sy) << 28 | 6 << 29,
             f"{'(sy)' if sy else ''}stg.u{ {2:16,3:32,6:8}[kind]} g[r2.z], r3.x, {count}")

    nop(4, True)
    # HLSQ supplies the workgroup origin at c2.yz and local IDs at r0.xy.
    alu('add.u', 'r1.x', 'c2.y', 'r0.x', True, True)
    alu('add.u', 'r1.y', 'c2.z', 'r0.y')
    nop()
    if fmt == 'copy':
        # Both sealed buffers use a 480-pixel stride. Origins are included in
        # c5.xy, never in a user-supplied address; each invocation copies U32.
        alu('mul.u', 'r2.x', 'r1.y', 'c5.z')
        alu('shl.b', 'r2.y', 'r1.x', '2')
        nop()
        alu('add.u', 'r2.x', 'r2.x', 'r2.y')
        nop()
        alu('add.u', 'r2.z', 'r2.x', 'c5.y')
        alu('add.u', 'r2.x', 'r2.x', 'c5.x')
        nop(5)
        emit(1 | register('r2.x') << 14 | 1 << 23 | 1 << 24,
             register('r3.x') | 3 << 17 | 6 << 29, 'ldg.u32 r3.x, g[r2.x], 1')
        nop(5, True)
        store(3, sy=True)
        emit(0, 6 << 23, 'end')
        while len(words) % 8:
            nop(0)
        return words, assembly
    # Exact floor(x*480/720) for 0<=x<720; floor(y*800/1280).
    alu('mul.u', 'r2.x', 'r1.x', 'c6.x')
    alu('mul.u', 'r2.y', 'r1.y', '5')
    nop()
    alu('shr.b', 'r2.x', 'r2.x', '15')
    alu('shr.b', 'r2.y', 'r2.y', '3')
    nop()
    alu('mul.u', 'r2.y', 'r2.y', '480')
    nop()
    alu('add.u', 'r2.x', 'r2.x', 'r2.y')
    nop()
    alu('shl.b', 'r2.x', 'r2.x', '2')
    nop()
    alu('add.u', 'r2.x', 'r2.x', 'c5.x')
    nop(5)
    # LDG uses the offset encoding even when its offset is zero.
    emit(1 | register('r2.x') << 14 | 1 << 23 | 1 << 24,
         register('r3.x') | 3 << 17 | 6 << 29, 'ldg.u32 r3.x, g[r2.x], 1')
    alu('mul.u', 'r2.z', 'r1.y', 'c5.z')
    alu('mul.u', 'r2.w', 'r1.x', 'c5.w')
    nop()
    alu('add.u', 'r2.z', 'r2.z', 'r2.w')
    nop()
    alu('add.u', 'r2.z', 'r2.z', 'c5.y')
    nop(5)
    if fmt == 'rgb888':
        alu('shr.b', 'r3.y', 'r3.x', '8', True)
        alu('shr.b', 'r3.z', 'r3.x', '16')
        nop(5)
        store(6, 3)
    elif fmt == 'rgb565':
        alu('shr.b', 'r3.y', 'r3.x', '8', True)
        alu('shr.b', 'r3.z', 'r3.x', '5')
        alu('shr.b', 'r3.x', 'r3.x', '3')
        nop()
        alu('and.b', 'r3.y', 'r3.y', 'c6.y')
        alu('and.b', 'r3.z', 'r3.z', 'c6.z')
        alu('and.b', 'r3.x', 'r3.x', '31')
        nop()
        alu('or.b', 'r3.x', 'r3.x', 'r3.y')
        nop()
        alu('or.b', 'r3.x', 'r3.x', 'r3.z')
        nop(5)
        store(2)
    elif fmt == 'argb8888':
        alu('or.b', 'r3.x', 'r3.x', 'c6.w', True)
        nop(5)
        store(3)
    else:
        store(3, sy=True)
    emit(0, 6 << 23, 'end')
    while len(words) % 8:
        nop(0)
    return words, assembly


def generate():
    header = ['/* Generated by tools/adreno_shader.py. See adreno-notices.txt. */',
              '#ifndef SOS2_ADRENO_SHADERS_H', '#define SOS2_ADRENO_SHADERS_H', '#include <stdint.h>']
    asm = ['; Fixed 480x800 -> 720x1280 nearest-neighbor display kernels.',
           '; c5: source IOVA, output IOVA, output stride, bytes/pixel.',
           '; c6: 21846, 0xf800, 0x7e0, 0xff000000.']
    for fmt in ('xrgb8888', 'rgb565', 'rgb888', 'argb8888', 'copy'):
        words, assembly = shader(fmt)
        header.append(f'static const uint32_t adreno_shader_{fmt}[] = {{')
        for i in range(0, len(words), 8):
            header.append('    ' + ','.join(f'0x{x:08x}' for x in words[i:i+8]) + ',')
        header.append('};')
        asm += ['', '; ' + fmt, *assembly]
    header.append('#endif')
    return {'adreno_shaders.h': '\n'.join(header)+'\n', 'adreno_scaler.asm': '\n'.join(asm)+'\n'}


if __name__ == '__main__':
    argparse.ArgumentParser(description=__doc__).parse_args()
    for name, content in generate().items():
        (ROOT/'boards/redmi2'/name).write_text(content)
